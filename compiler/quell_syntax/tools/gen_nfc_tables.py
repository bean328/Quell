"""Generates compiler/quell_syntax/src/lexer/nfc_tables.rs.

The lexer checks that identifiers are in Unicode Normalization Form C
(spec/lexical.md, section 5.1). These tables hold the three pieces of the
Unicode Character Database that NFC needs: canonical combining classes,
canonical decompositions and the pairs that compose. Hangul syllables are
handled by the algorithm in nfc.rs and are not in the tables.

Run from the repository root:

    python3 compiler/quell_syntax/tools/gen_nfc_tables.py

The Unicode version is the one built into Python's unicodedata module.
"""

import sys
import unicodedata as ud
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "lexer" / "nfc_tables.rs"


def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3


def main():
    ccc_ranges = []
    decompositions = []
    compositions = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        ccc = ud.combining(ch)
        if ccc:
            last = ccc_ranges[-1] if ccc_ranges else None
            if last and last[1] == cp - 1 and last[2] == ccc:
                last[1] = cp
            else:
                ccc_ranges.append([cp, cp, ccc])
        if is_hangul_syllable(cp):
            continue
        d = ud.decomposition(ch)
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        assert 1 <= len(parts) <= 2, (hex(cp), parts)
        decompositions.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
        if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch:
            compositions.append((parts[0], parts[1], cp))
    compositions.sort()

    lines = [
        "//! Unicode data for NFC normalization. Generated by",
        "//! `compiler/quell_syntax/tools/gen_nfc_tables.py`; do not edit by hand.",
        f"//! Unicode version: {ud.unidata_version}.",
        "",
        "/// Ranges of characters with a non-zero canonical combining class: (first, last, class).",
        "#[rustfmt::skip]",
        "pub(super) static COMBINING_CLASSES: &[(u32, u32, u8)] = &[",
    ]
    lines += rows([f"(0x{a:X}, 0x{b:X}, {c})" for a, b, c in ccc_ranges])
    lines += [
        "];",
        "",
        "/// Canonical decompositions: (character, first, second). `second` is 0 for a",
        "/// decomposition into one character.",
        "#[rustfmt::skip]",
        "pub(super) static DECOMPOSITIONS: &[(u32, u32, u32)] = &[",
    ]
    lines += rows([f"(0x{a:X}, 0x{b:X}, 0x{c:X})" for a, b, c in decompositions])
    lines += [
        "];",
        "",
        "/// Pairs that compose into one character: (first, second, composed), sorted.",
        "#[rustfmt::skip]",
        "pub(super) static COMPOSITIONS: &[(u32, u32, u32)] = &[",
    ]
    lines += rows([f"(0x{a:X}, 0x{b:X}, 0x{c:X})" for a, b, c in compositions])
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(ccc_ranges)} ranges, {len(decompositions)} decompositions, "
          f"{len(compositions)} compositions)", file=sys.stderr)


def rows(items, width=96):
    out = []
    line = "   "
    for item in items:
        if len(line) + 1 + len(item) + 1 > width:
            out.append(line)
            line = "   "
        line += " " + item + ","
    if line.strip():
        out.append(line)
    return out


if __name__ == "__main__":
    main()
